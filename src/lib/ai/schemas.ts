import { z } from 'zod';

/**
 * Способ приготовления заметно меняет калорийность одного и того же продукта:
 * 100 г варёной картошки и 100 г жареной различаются больше чем вдвое.
 * Поэтому он входит в поисковый запрос к справочнику нутриентов.
 */
export const preparationSchema = z.enum([
  'raw',
  'boiled',
  'fried',
  'baked',
  'grilled',
  'steamed',
  'stewed',
  'unknown',
]);

export type Preparation = z.infer<typeof preparationSchema>;

/**
 * Что помешало точной оценке.
 *
 * Кодом, а не фразой — по той же причине, по которой калорийность берётся
 * из справочника. Свободный текст модель пишет на языке промпта, то есть
 * по-русски, и в казахском интерфейсе он выглядит как сбой приложения.
 * Перевести его на лету нельзя: перевод — это ещё один вызов модели на
 * каждую позицию. Заодно текст перестал быть невоспроизводимым: одна и та
 * же причина каждый раз формулировалась по-новому.
 *
 * Список короткий намеренно. Чем больше кодов, тем чаще модель выбирает
 * близкий, но не тот, — а предупреждение не по делу человек перестаёт
 * читать вместе с теми, что по делу.
 */
export const uncertaintySchema = z.enum([
  'none', // всё однозначно
  'portion_size', // в кадре не по чему определить масштаб
  'hidden_ingredients', // масло, соус, начинка — их не видно
  'cooking_method', // непонятно, как приготовлено
  'obscured', // блюдо частично скрыто или снято под углом
  'similar_dishes', // похоже сразу на несколько блюд
]);

export type Uncertainty = z.infer<typeof uncertaintySchema>;

/** Замечание к разбору целиком — тоже кодом, тоже ради языка интерфейса */
export const recognitionNoteSchema = z.enum([
  'none',
  'shared_plate', // порция выглядит рассчитанной на нескольких
  'partially_eaten', // часть уже съедена, вес относится к остатку
  'unclear_photo', // снимок тёмный, размытый или слишком далёкий
]);

export type RecognitionNote = z.infer<typeof recognitionNoteSchema>;

export const recognizedItemSchema = z.object({
  /** Название на русском — его увидит пользователь на экране подтверждения */
  nameRu: z.string().describe('Название продукта или блюда по-русски'),
  /** Английское название — по нему ищем в USDA FoodData Central */
  nameEn: z
    .string()
    .describe('Общепринятое английское название для поиска в базе нутриентов'),
  /** Оценка веса съеденного. Пользователь поправит её перед сохранением. */
  grams: z.number().describe('Оценка веса порции в граммах'),
  confidence: z
    .number()
    .describe('Уверенность в определении продукта и веса, от 0 до 1'),
  // Тоже с мягкой посадкой: способ приготовления уточняет поиск по
  // справочнику, но ради него терять весь разбор незачем — «unknown»
  // здесь штатное значение
  preparation: preparationSchema.catch('unknown').describe('Способ приготовления'),
  /**
   * Что именно мешало точности — показываем при низкой уверенности.
   *
   * `.catch` здесь не перестраховка. Список кодов уходит в схему ответа,
   * и модель обязана выбрать из него, но однажды она вернула значение вне
   * списка — и разбор упал целиком, вместе с распознанным составом. Цена
   * несопоставима: пропущенное предупреждение против потерянной записи,
   * которую человек уже сфотографировал.
   */
  uncertainty: uncertaintySchema
    .catch('none')
    .describe('Что мешает точной оценке. none, если всё однозначно'),
});

export type RecognizedItem = z.infer<typeof recognizedItemSchema>;

export const recognitionSchema = z.object({
  /** false — на фото не еда; бот ответит понятной ошибкой вместо мусора */
  isFood: z.boolean().describe('Есть ли на изображении или в описании еда'),
  mealType: z
    .enum(['breakfast', 'lunch', 'dinner', 'snack'])
    .describe('Предполагаемый приём пищи по составу блюд'),
  items: z
    .array(recognizedItemSchema)
    .describe('Отдельные продукты и блюда; составное блюдо не разбирается на ингредиенты'),
  /** Замечание к разбору целиком, а не к отдельной позиции */
  note: recognitionNoteSchema
    .catch('none')
    .describe('Замечание ко всему разбору. none, если замечаний нет'),
});

export type Recognition = z.infer<typeof recognitionSchema>;

/* ─────────────────── Результат работы модуля ───────────────────────── */

/**
 * Отказ описывается кодом, а не фразой: текст для пользователя лежит
 * в словарях (`bot.failure.*`) и зависит от его языка, а модуль
 * распознавания языка интерфейса не знает.
 */
export type RecognitionOutcome =
  | { ok: true; recognition: Recognition; meta: RecognitionMeta }
  | { ok: false; reason: RecognitionFailure };

export type RecognitionFailure =
  | 'not_food' // на фото не еда
  | 'refused' // сработали классификаторы безопасности
  | 'empty' // модель не вернула ни одной позиции
  | 'malformed' // ответ не прошёл валидацию схемы
  | 'api_error'; // сеть, лимиты, недоступность

export interface RecognitionMeta {
  model: string;
  latencyMs: number;
  /** Токены, обработанные по полной цене (изображение и переменная часть) */
  inputTokens: number;
  outputTokens: number;
  /** Прочитано из кеша — стоит 0.1× от входной цены */
  cacheReadTokens: number;
  /**
   * Записано в кеш — стоит 1.25× от входной цены. Без этого поля учёт
   * занижает стоимость: системный промпт при холодном кеше оплачивается
   * с наценкой, а не бесплатно.
   */
  cacheWriteTokens: number;
}

