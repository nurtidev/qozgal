/** Подсказка модели о времени суток — помогает угадать приём пищи */
export function buildTimeHint(localHour: number): string {
  if (localHour >= 5 && localHour < 11) return 'Сейчас утро.';
  if (localHour >= 11 && localHour < 16) return 'Сейчас день.';
  if (localHour >= 16 && localHour < 22) return 'Сейчас вечер.';
  return 'Сейчас ночь.';
}
